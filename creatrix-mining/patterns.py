#!/usr/bin/env python3
"""Rank root-cause clusters by frequency x cost and write ~/Development/creatrix-lessons/patterns.md.

frequency = sum(recurrence_count) over incidents in the cluster.
cost per incident = TYPE_WEIGHT[type] x (1.5 if a user_quote exists, i.e. the user hit it and said so) x recurrence_count.
Weights encode rework cost seen in the ledger: false-done claims and regressions burn a user round-trip + re-fix.
"""
import json, re, collections
from schema import LESSONS

TYPE_WEIGHT = {"bug": 1.0, "spec-gap": 1.5, "process-failure": 1.5, "regression": 2.0, "revert": 2.0,
               "design-reversal": 2.0, "misunderstanding": 2.0, "false-done-claim": 3.0}

def taxonomy():
    t = {}
    for l in open(__file__.rsplit("/", 1)[0] + "/RC_TAXONOMY.md"):
        m = re.match(r"\| (RC\d\d) \| ([^|]+)\| ([^|]+)\| ([^|]+)\|", l)
        if m: t[m[1]] = (m[2].strip(), m[3].strip(), m[4].strip())
    return t

def main():
    rows = [json.loads(l) for l in open(f"{LESSONS}/ledger.jsonl")]
    tax = taxonomy()
    agg = collections.defaultdict(lambda: {"n": 0, "freq": 0, "score": 0.0, "rows": [], "types": collections.Counter(),
                                           "areas": collections.Counter(), "quotes": 0})
    for r in rows:
        c = r.get("root_cause_cluster") or "RC99"
        w = TYPE_WEIGHT[r["type"]] * (1.5 if r.get("user_quote") else 1.0)
        a = agg[c]; a["n"] += 1; a["freq"] += r["recurrence_count"]; a["score"] += w * r["recurrence_count"]
        a["types"][r["type"]] += 1; a["areas"][r["area"]] += 1; a["quotes"] += bool(r.get("user_quote"))
        a["rows"].append((r["recurrence_count"] * w, len(r["sources"]), r))
    ranked = sorted(agg.items(), key=lambda kv: -kv[1]["score"])
    total = sum(a["score"] for _, a in ranked)
    out = ["# Creatrix root-cause patterns", "",
           f"Generated by `tools/creatrix-mining/patterns.py` from `ledger.jsonl` ({len(rows)} incidents). "
           "Rank = Σ(recurrence × type-weight × 1.5 if user-quoted). "
           "Type weights: " + ", ".join(f"{k} {v}" for k, v in TYPE_WEIGHT.items()) + ".", "",
           "| rank | cluster | incidents | Σ recurrences | user-quoted | score | share | plan-time check |",
           "|---|---|---|---|---|---|---|---|"]
    for i, (c, a) in enumerate(ranked, 1):
        name, _, check = tax.get(c, ("other", "", "—"))
        out.append(f"| {i} | {c} {name} | {a['n']} | {a['freq']} | {a['quotes']} | {a['score']:.0f} | "
                   f"{100 * a['score'] / total:.1f}% | {check} |")
    for i, (c, a) in enumerate(ranked, 1):
        name, mech, check = tax.get(c, ("other", "", "—"))
        out += ["", f"## {i}. {c} {name}", "",
                f"**Mechanism:** {mech}  ", f"**Plan-time check:** {check}  ",
                f"**Incidents:** {a['n']} · **Σ recurrences:** {a['freq']} · **score:** {a['score']:.0f} · "
                f"**types:** {dict(a['types'].most_common(4))} · **areas:** {dict(a['areas'].most_common(4))}", "",
                "Examples (highest recurrence × cost, multi-source first):", ""]
        for _, _, r in sorted(a["rows"], key=lambda x: (-x[0], -x[1], x[2]["date"]))[:3]:
            q = f' — user: "{r["user_quote"][:120]}"' if r.get("user_quote") else ""
            out.append(f"- `{r['id']}` {r['date']} [{r['type']}/{r['area']}] ×{r['recurrence_count']} — {r['symptom'][:160]} "
                       f"(ref `{r['source_ref']}`{', fix `' + r['fix_ref'] + '`' if r.get('fix_ref') else ''}){q}")
    open(f"{LESSONS}/patterns.md", "w").write("\n".join(out) + "\n")
    print(f"clusters={len(ranked)} top3=" + ", ".join(f"{c}({a['score']:.0f})" for c, a in ranked[:3]))

if __name__ == "__main__":
    main()
